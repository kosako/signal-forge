-- GH#235: 未消化一覧への本人の操作(パス・指定)の受付の順序の印(設計 06 §6)。
-- 深掘りカードへの調べ直しの依頼は、質問を受け付けてから返事を作り終えるまで数分かかる。
-- その間に本人が未消化一覧で同じアイテムをパス・指定し直していたら、作り終えた古い依頼で
-- 上書きしない。時刻(秒の単位)では同じ秒の先後が分からないので、質問の id を目盛りにする。
-- backlog_op_question_id = 未消化一覧への最後の操作を反映した時点で、受け付け済みだった質問
-- (dig_questions.id)の最大(質問がまだ無ければ 0)。調べ直しの依頼は、自分の id がこれ以下なら
-- (操作より前に受け付けた)積まない。調べ直しの依頼と朝の深掘りの done は変えない。
-- NULL = 未消化一覧での操作がまだない(この migration より前の操作を含む)。
ALTER TABLE dig_queue ADD COLUMN backlog_op_question_id INTEGER;
